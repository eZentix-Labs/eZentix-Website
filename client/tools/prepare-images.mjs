import sharp from 'sharp'
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = resolve(root, 'public')
const workDir = resolve(publicDir, 'work/hotel-khoai')
const variants = {}
// Keep full-size originals and JPEG fallback. Smaller WebPs are used only
// for cards/thumbnails; opening the image still shows the original file.
for (const name of readdirSync(workDir).filter((name) => name.endsWith('.webp') && !/-\d+w\.webp$/.test(name))) {
  const source = resolve(workDir, name)
  const { width, height } = await sharp(source).metadata()
  const candidates = []
  for (const size of [480, 800]) {
    if (size >= width) continue
    const target = name.replace('.webp', `-${size}w.webp`)
    await sharp(source).resize({ width: size, withoutEnlargement: true }).webp({ quality: 85 }).toFile(resolve(workDir, target))
    candidates.push(`/work/hotel-khoai/${target} ${size}w`)
  }
  const url = `/work/hotel-khoai/${name}`
  candidates.push(`${url} ${width}w`)
  variants[url] = { width, height, srcSet: candidates.join(', ') }
  if (name === 'cover.webp') variants[url.replace('.webp', '.jpg')] = variants[url]
}
await sharp(resolve(publicDir, 'logo.svg'), { density: 144 })
  .resize(148, 148, { fit: 'contain' })
  .extend({ top: 16, bottom: 16, left: 16, right: 16, background: '#ffffff' })
  .flatten({ background: '#ffffff' }).png().toFile(resolve(publicDir, 'apple-touch-icon.png'))
writeFileSync(resolve(root, 'src/data/image-variants.js'),
  `// Generated by tools/prepare-images.mjs from existing artwork.\nexport const imageVariants = ${JSON.stringify(variants, null, 2)}\n`)
console.log('[images] generated WebP variants, dimensions and 180x180 PNG touch icon')
