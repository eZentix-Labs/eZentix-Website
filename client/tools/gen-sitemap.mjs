#!/usr/bin/env node
/*
 * Writes public/sitemap.xml and public/robots.txt from the route table in
 * src/seo/site.js, so the two can never disagree with the router.
 *
 * Runs automatically on `npm run build` via the prebuild script.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { ORIGIN, ROUTES, abs } from '../src/seo/site.js'

const PUBLIC_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'public')

const urls = ROUTES.filter((r) => r.indexable)
  .map(
    (r) => `  <url>
    <loc>${abs(r.path)}</loc>
    <changefreq>${r.changefreq}</changefreq>
    <priority>${r.priority.toFixed(1)}</priority>
  </url>`,
  )
  .join('\n')

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`


const robots = `# ${ORIGIN}
# Generated by tools/gen-sitemap.mjs - edit src/seo/site.js, not this file.

User-agent: *
Allow: /

Sitemap: ${abs('/sitemap.xml')}
`

writeFileSync(resolve(PUBLIC_DIR, 'sitemap.xml'), sitemap)
writeFileSync(resolve(PUBLIC_DIR, 'robots.txt'), robots)

console.log(`[seo] wrote sitemap.xml (${ROUTES.filter((r) => r.indexable).length} urls) and robots.txt`)
